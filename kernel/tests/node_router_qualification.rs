#[test]
fn exact_host_route_casefold_and_alias_conflict() {
    let calls = Arc::new(Mutex::new(vec![]));
    let c = calls.clone();
    let mut r = Router::new(move |op, a| {
        assert_eq!(op, "router.read");
        c.lock().unwrap().push(a["record"]["node_id"].clone());
        Ok(json!({"result":found(&a["request"])}))
    });
    let mut air = record("air");
    air["route_ids"] = json!(["Straße"]);
    r.attach(air, false);
    assert_eq!(
        r.read(json!({"thread_id":"t","host":"STRASSE"})).unwrap()["source_node_id"],
        "air"
    );
    assert_eq!(*calls.lock().unwrap(), vec![json!("air")]);
    let mut imac = record("imac");
    imac["route_ids"] = json!(["strasse"]);
    r.attach(imac, false);
    assert_eq!(
        r.read(json!({"thread_id":"t","host":"STRASSE"}))
            .unwrap_err(),
        "THREAD_HOST_CONFLICT"
    );
}
#[test]
fn authorized_search_requires_exact_evidence_and_reports_conflicts() {
    let exact = Arc::new(Mutex::new(false));
    let e = exact.clone();
    let mut r = Router::new(move |_, a| {
        let mut result = found(&a["request"]);
        if a["record"]["node_id"] == "imac" && !*e.lock().unwrap() {
            result["queried_thread_id"] = json!("another");
        }
        Ok(json!({"result":result}))
    });
    r.args["max_workers"] = json!(2);
    r.attach(record("air"), false);
    r.attach(record("imac"), false);
    let result = r.read(json!({"thread_id":"t"})).unwrap();
    assert_eq!(result["source_node_id"], "air");
    assert_eq!(result["coverage"]["complete"], false);
    assert_eq!(result["coverage"]["nodes_unavailable"], json!(["imac"]));
    *exact.lock().unwrap() = true;
    let result = r.read(json!({"thread_id":"t"})).unwrap();
    assert_eq!(result["error_code"], "THREAD_IDENTITY_CONFLICT");
    assert_eq!(result["matching_nodes"], json!(["air", "imac"]));
    r.registry
        .call(
            "registry.revoke",
            json!({"node_id":"air","user_scope":"alice"}),
        )
        .unwrap();
    assert_eq!(
        r.read(json!({"thread_id":"t","node_id":"air"})).unwrap()["error_code"],
        "SHARING_SCOPE_DENIED"
    );
}
