fn helper_native_read_uses_exact_rust_metadata_and_project_scope() {
    let temp = tempfile::tempdir().unwrap();
    let native = temp.path().join("native");
    std::fs::create_dir(&native).unwrap();
    let db = rusqlite::Connection::open(native.join("state_5.sqlite")).unwrap();
    db.execute_batch("CREATE TABLE threads (id TEXT,cwd TEXT,rollout_path TEXT); INSERT INTO threads VALUES ('t','/project','');").unwrap();
    drop(db);
    let calls = Arc::new(Mutex::new(vec![]));
    let current = Arc::new(Mutex::new("/other"));
    let (c, s) = (calls.clone(), current.clone());
    let w = Worker::new(move |e| {
        let op = e["operation"].as_str().unwrap();
        c.lock().unwrap().push(op.to_owned());
        if op == "helper.scopes" {
            let mut scope = scope(false);
            scope["projects"] = json!([*s.lock().unwrap()]);
            Ok(json!({"local":scope,"active":scope}))
        } else {
            assert_eq!(op, "helper.context");
            let mut a = e["arguments"].clone();
            a["exact"] = json!(true);
            Ok(a)
        }
    });
    let mut a = json!({"native_home":native,"node_id":"air","kwargs":{},"execution":true,"thread_id":"missing"});
    assert_eq!(
        w.call("router.helper_read", a.clone()).unwrap()["provider_existence"],
        "NOT_FOUND"
    );
    assert!(calls.lock().unwrap().is_empty());
    a["thread_id"] = json!("t");
    assert_eq!(
        w.call("router.helper_read", a.clone()).unwrap()["error_code"],
        "PROJECT_SCOPE_DENIED"
    );
    assert_eq!(*calls.lock().unwrap(), vec!["helper.scopes"]);
    *current.lock().unwrap() = "/project";
    assert_eq!(
        w.call("router.helper_read", a.clone()).unwrap(),
        json!({"exact":true,"host":"air","thread_id":"t"})
    );
    assert_eq!(
        *calls.lock().unwrap(),
        vec!["helper.scopes", "helper.scopes", "helper.context"]
    );
    a["native_home"] = json!(temp.path().join("absent"));
    let result = w.call("router.helper_read", a).unwrap();
    assert_eq!(result["error_code"], "NATIVE_INDEX_UNAVAILABLE");
    assert_eq!(result["provider_existence"], "UNKNOWN");
}
#[test]
fn helper_supervisor_registers_once_schedules_and_fails_closed_on_restart() {
    let calls = Arc::new(Mutex::new(Vec::<(String, Value)>::new()));
    let a =
        json!({"centre_id":"p620","node_id":"air","endpoint":"tls://fixture:1","capabilities":[]});
    for lost in [false, true] {
        calls.lock().unwrap().clear();
        let c = calls.clone();
        let w = Worker::new(move |e| {
            let op = e["operation"].as_str().unwrap();
            c.lock().unwrap().push((op.into(), e["arguments"].clone()));
            let result = match op {
                "helper.approval" => scope(true),
                "helper.register" => {
                    if lost {
                        return Ok(json!({"error_type":"TimeoutError"}));
                    }
                    json!({"registered":true,"scope":scope(true),"heartbeat_seconds":3})
                }
                "helper.collect" => json!({"delay":30,"status":"INDEXED","sampled":1}),
                _ => Value::Null,
            };
            Ok(json!({"result":result}))
        });
        assert_eq!(
            w.call("router.helper_tick", a.clone()).unwrap()["active"],
            !lost
        );
        let count = calls.lock().unwrap().len();
        assert_eq!(
            w.call("router.helper_tick", a.clone()).unwrap()["active"],
            !lost
        );
        assert_eq!(calls.lock().unwrap().len(), count);
        let calls = calls.lock().unwrap();
        assert_eq!(
            calls
                .iter()
                .filter(|(op, _)| op == "helper.register")
                .map(|(_, a)| a["heartbeat"].clone())
                .collect::<Vec<_>>(),
            vec![json!(false)]
        );
        assert_eq!(
            calls
                .iter()
                .filter(|(op, _)| op == "helper.state")
                .map(|(_, a)| a.clone())
                .collect::<Vec<_>>(),
            vec![if lost {
                json!({"state":"OFFLINE"})
            } else {
                json!({"state":"ONLINE","last_seen":null})
            }]
        );
        if lost {
            assert_eq!(
                calls
                    .iter()
                    .filter(|(op, _)| op == "helper.active")
                    .map(|(_, a)| a.clone())
                    .collect::<Vec<_>>(),
                vec![Value::Null]
            );
        }
    }
}
