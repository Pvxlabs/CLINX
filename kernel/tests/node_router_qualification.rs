fn found(q: &Value) -> Value {
    json!({"queried_thread_id":q["thread_id"],"lookup_status":"THREAD_UNBOUND","provider_existence":"CONFIRMED"})
}
fn absent(q: &Value) -> Value {
    json!({"queried_thread_id":q["thread_id"],"lookup_status":"THREAD_NOT_FOUND","provider_existence":"NOT_FOUND"})
}
struct Router {
    _temp: tempfile::TempDir,
    registry: Arc<Worker>,
    worker: Worker,
    args: Value,
}
impl Router {
    fn new(io: impl Fn(&str, Value) -> Result<Value> + Send + Sync + 'static) -> Self {
        let temp = tempfile::tempdir().unwrap();
        let registry = registry(&temp.path().join("nodes.db"));
        let r = registry.clone();
        let worker = Worker::new(move |e| {
            let op = e["operation"].as_str().unwrap();
            let a = e["arguments"].clone();
            if op.starts_with("registry.") {
                registry_call(&r, op, a)
            } else if matches!(op, "router.reader" | "router.executor") {
                Ok(json!(true))
            } else {
                io(op, a)
            }
        });
        Self {
            _temp: temp,
            registry,
            worker,
            args: json!({"user_scope":"alice","local_node_id":null,"local_readers":[],"executors":[],"max_workers":4,"timeout_seconds":2.0}),
        }
    }
    fn attach(&mut self, r: Value, execute: bool) {
        self.registry
            .call(
                "registry.register",
                json!({"record":r,"scope":scope(execute)}),
            )
            .unwrap();
        self.args["local_readers"]
            .as_array_mut()
            .unwrap()
            .push(r["node_id"].clone());
        if execute {
            self.args["executors"]
                .as_array_mut()
                .unwrap()
                .push(r["node_id"].clone());
        }
    }
    fn call(&self, op: &str, a: Value) -> Result<Value> {
        let mut args = self.args.clone();
        args.as_object_mut()
            .unwrap()
            .extend(a.as_object().unwrap().clone());
        self.worker.call(&format!("router.{op}"), args)
    }
    fn read(&self, mut a: Value) -> Result<Value> {
        a["provider"] = json!("codex_app_server");
        a["recent_turns"] = json!(8);
        a["max_bytes"] = json!(32000);
        self.call("read", a)
    }
    fn reference(&self, id: &str) -> Value {
        self.registry
            .call(
                "registry.reference_node",
                json!({"reference":id,"user_scope":"alice"}),
            )
            .unwrap()
    }
}
