fn canonical_ack_conflict_is_not_published_as_success() {
    let task = Arc::new(Mutex::new("wrong"));
    let t = task.clone();
    let mut r = Router::new(move |_, _| {
        Ok(json!({"result":{"task_ref":*t.lock().unwrap(),"execution_ref":"exec"}}))
    });
    r.attach(record("air"), true);
    let a = json!({"node_id":"air","operation":"execution.adopt","request":{"canonical_identity":{"task_id":"exact"}}});
    let result = r.call("execute", a.clone()).unwrap();
    assert_eq!(result["error_code"], "CANONICAL_HANDOFF_ACK_CONFLICT");
    assert_eq!(result["side_effect"], "UNKNOWN");
    assert_eq!(r.reference("exec"), Value::Null);
    *task.lock().unwrap() = "exact";
    assert_eq!(r.call("execute", a).unwrap()["task_ref"], "exact");
    assert_eq!(r.reference("exec"), "air");
}
