#[test]
fn reverse_authority_ack_identity_frame_limit_and_no_replay() {
    let sent = Arc::new(Mutex::new(vec![]));
    let response = Arc::new(Mutex::new(Ok(
        json!({"request_id":"one","result":{"task_ref":"t"}}),
    )));
    let (s, r) = (sent.clone(), response.clone());
    let w = Worker::new(move |e| {
        assert_eq!(e["operation"], "authority.request");
        s.lock().unwrap().push(e["arguments"].clone());
        r.lock().unwrap().clone()
    });
    let mut a = json!({"operation":"business.prepare","payload":{"prompt":"exact"},"request_id":"one","node_id":"air","scope":scope(true)});
    assert_eq!(
        w.call("router.authority_request", a.clone()).unwrap(),
        json!({"task_ref":"t"})
    );
    assert_eq!(sent.lock().unwrap()[0]["command"], "prepare");
    assert_eq!(sent.lock().unwrap()[0]["node_id"], "air");
    a["payload"] = json!({});
    *response.lock().unwrap() = Ok(json!({"request_id":"another","result":{"task_ref":"t"}}));
    assert_eq!(
        w.call("router.authority_request", a.clone()).unwrap_err(),
        "DELIVERY_UNKNOWN"
    );
    *response.lock().unwrap() = Err("PROVIDER_DELIVERY_UNKNOWN".into());
    assert_eq!(
        w.call("router.authority_request", a.clone()).unwrap_err(),
        "DELIVERY_UNKNOWN"
    );
    assert_eq!(sent.lock().unwrap().len(), 3);
    a["payload"] = json!({"prompt":"线程".repeat(23000)});
    a["request_id"] = json!("large");
    assert_eq!(
        w.call("router.authority_request", a.clone()).unwrap_err(),
        "REQUEST_TOO_LARGE"
    );
    a["payload"] = json!({});
    a["operation"] = json!("arbitrary.start");
    a["request_id"] = json!("denied");
    assert_eq!(
        w.call("router.authority_request", a.clone()).unwrap_err(),
        "UNSUPPORTED_OPERATION"
    );
    a["operation"] = json!("business.prepare");
    a["scope"] = scope(false);
    assert_eq!(
        w.call("router.authority_request", a).unwrap_err(),
        "SHARING_SCOPE_DENIED"
    );
    assert_eq!(sent.lock().unwrap().len(), 3);
}
